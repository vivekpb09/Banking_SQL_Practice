USE BANK;
DESC CUSTOMERS;
DESC ACCOUNTS;

SELECT A.CUSTOMER_ID, C.BALANCE
FROM CUSTOMERS A LEFT JOIN ACCOUNTS C
ON A.CUSTOMER_ID = C.ACCOUNT_ID
WHERE C.BALANCE IS NULL;



DESC CUSTOMERS;
DESC ACCOUNTS;
DESC BRANCHES;

SELECT A.FIRST_NAME,B.BRANCH_NAME,C.ACCOUNT_TYPE,C.BALANCE
FROM CUSTOMERS A LEFT JOIN BRANCHES B 
ON A.CUSTOMER_ID = B.BRANCH_ID
LEFT JOIN ACCOUNTS C
ON B.BRANCH_ID = C.ACCOUNT_ID;



